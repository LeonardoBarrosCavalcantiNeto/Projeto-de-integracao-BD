-- 01 — Camada RAW
-- As 20 colunas originais ficam como TEXT para preservar os valores recebidos.
-- id_raw é uma chave técnica; arquivo_origem e linha_origem são metadados.
-- Não aplicar limpeza, conversão ou deduplicação nesta tabela.

CREATE TABLE raw.voos_2019 (
    id_raw BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla_icao_empresa_aerea TEXT,
    empresa_aerea TEXT,
    numero_voo TEXT,
    codigo_di TEXT,
    codigo_tipo_linha TEXT,
    modelo_equipamento TEXT,
    numero_assentos TEXT,
    sigla_icao_aeroporto_origem TEXT,
    descricao_aeroporto_origem TEXT,
    partida_prevista TEXT,
    partida_real TEXT,
    sigla_icao_aeroporto_destino TEXT,
    descricao_aeroporto_destino TEXT,
    chegada_prevista TEXT,
    chegada_real TEXT,
    situacao_voo TEXT,
    justificativa TEXT,
    referencia TEXT,
    situacao_partida TEXT,
    situacao_chegada TEXT,
    arquivo_origem TEXT,
    linha_origem BIGINT
);

